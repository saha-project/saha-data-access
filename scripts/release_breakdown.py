#!/usr/bin/env python3
"""
release_breakdown.py
Write docs/RELEASE_BREAKDOWN.md -- what ships where: Zenodo v1, AWS v1 and the
AWS v2 queue, by organ and modality, reconciled against Table 1, with the
directory tree of each. Every number is read from a table; nothing is typed in.

Inputs
    data/samples.parquet, data/v2/samples.parquet   what each release contains
    zenodo/measurements.csv                        acquisition x donor core
    zenodo/cohort_coverage.csv                     donor core vs Table 1
    zenodo/combined_manifest.csv                   packaged Zenodo zips (sizes)
    aws/store_sizes.tsv                            per-store bytes on Cayuga: tier\tstore\tbytes,
                                                   tier = s3 | zenodo_tier | s3_v2
    aws/raw_manifest.csv                           raw upload plan
    Table_1.xlsx (manuscript)                      optional; row counts only

Usage:
    python scripts/release_breakdown.py
"""

import numbers
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from package_for_zenodo import record_slug, sample_id_of  # noqa: E402

REPO = Path(__file__).resolve().parent.parent
TABLE1 = Path("/Users/jiwoonpark/Dropbox (Personal)/2025- MasonLab/2025_SAHA/"
              "Publication/Revision/Submission/Upload/Tables/Table_1.xlsx")
GB = 1e9


def fmt(n):
    return f"{int(n):,}"


def md_table(df):
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join("---:" if pd.api.types.is_numeric_dtype(df[c])
                                                         else "---" for c in cols) + "|"]
    for r in df.itertuples(index=False):
        out.append("| " + " | ".join(fmt(v) if isinstance(v, numbers.Integral) and not isinstance(v, bool)
                                       else (f"{v:,.1f}" if isinstance(v, numbers.Real) and not isinstance(v, bool)
                                             else str(v)) for v in r) + " |")
    return "\n".join(out)


def modality(r):
    return f"{'CosMx' if r.platform == 'cosmx' else 'Xenium'} {r.assay_type.upper() if r.assay_type == 'rna' else 'protein'} · {r.panel_name}"


def main():
    s = pd.read_parquet(REPO / "data/samples.parquet")
    s["record"] = s.apply(record_slug, axis=1)
    s["modality"] = s.apply(modality, axis=1)
    meas = pd.read_csv(REPO / "zenodo/measurements.csv")
    cov = pd.read_csv(REPO / "zenodo/cohort_coverage.csv")
    zman = pd.read_csv(REPO / "zenodo/combined_manifest.csv")
    sizes = pd.read_csv(REPO / "aws/store_sizes.tsv", sep="\t", names=["dir", "store", "bytes"])
    sizes["sample_id"] = [sample_id_of(Path(x + ".zarr")) for x in sizes.store]
    raw = pd.read_csv(REPO / "aws/raw_manifest.csv")
    v2 = pd.read_parquet(REPO / "data/v2/samples.parquet")

    # sizes per tier, per sample
    z_bytes = zman.set_index("sample_id").size_bytes
    aws = sizes[sizes.dir == "s3"].set_index("sample_id").bytes
    assert set(aws.index) == set(s.sample_id), "AWS tier does not hold exactly the v1 samples"
    assert set(z_bytes.index) == set(s.sample_id), "Zenodo zips do not hold exactly the v1 samples"
    s["zenodo_gb"] = s.sample_id.map(z_bytes) / GB
    s["aws_gb"] = s.sample_id.map(aws) / GB
    cores = meas.groupby("sample_id").donor_core.nunique()
    s["cores"] = s.sample_id.map(cores).fillna(0).astype(int)
    v2_sizes = sizes[sizes.dir == "s3_v2"].set_index("store").bytes
    raw_in = raw[raw.include]

    L = ["# SAHA release breakdown", "",
         "Generated by `scripts/release_breakdown.py` from the release tables -- rerun it, don't edit by hand.", ""]

    # --- headline
    head = pd.DataFrame([
        dict(Release="Zenodo v1", Objects=len(s), Cells=int(s.n_cells.sum()),
             Cores=int(cov.in_release.sum()), Size=f"{s.zenodo_gb.sum():.1f} GB in 12 records + parent",
             Imagery="CosMx morphology 4x downsampled; Xenium native", Status="packaged, verified"),
        dict(Release="AWS v1", Objects=len(s), Cells=int(s.n_cells.sum()),
             Cores=int(cov.in_release.sum()),
             Size=f"{s.aws_gb.sum():.1f} GB processed + {raw_in.bytes.sum() / 1e12:.2f} TB raw",
             Imagery="full resolution",
             Status="built, verified; public interim copy s3://saha-public (Wasabi); AWS bucket pending"),
        dict(Release="AWS v2 (queue)", Objects=len(v2_sizes), Cells=int(v2.n_cells.sum()),
             Cores="31 (A2); A3 pending",  # from data/v2/STATUS.md -- v2 has no measurements.csv yet
             Size=f"{v2_sizes.sum() / GB:.1f} GB processed",
             Imagery="full resolution", Status="built, verified; private until publication"),
    ])
    L += ["## At a glance", "", md_table(head), "",
          "Zenodo and AWS v1 hold the **same 126 objects** (same sample ids, same cells, same "
          "labels). AWS swaps in full-resolution morphology for the 49 CosMx objects; the 52 Dulai "
          "and 25 Xenium (vendor-native imagery) objects are one store serving both. "
          "AWS sizes are the stores as uploaded to s3://saha-public, including the H&E images "
          "(same-section, serial-section and unaligned) added in October. Zenodo sizes come from "
          "zenodo/combined_manifest.csv, which predates the 2026-10-09/10 repackaging that added the "
          "H&E (the zips on Cayuga now total 199.0 GB, every record still under 50 GB); regenerate "
          "the manifest's sizes and MD5s before deposit. "
          "v2 cores: 31 resolved on PROS_A2; PROS_A3 is not yet resolved.", ""]

    # --- by organ x modality
    piv = s.pivot_table(index="organ", columns="modality", values="sample_id", aggfunc="count", fill_value=0)
    by_organ = s.groupby("organ").agg(Acquisitions=("sample_id", "size"), Cells=("n_cells", "sum"),
                                      Cores=("cores", "sum"), Zenodo_GB=("zenodo_gb", "sum"),
                                      AWS_GB=("aws_gb", "sum"))
    t = piv.join(by_organ).reset_index()
    t.loc[len(t)] = ["**total**"] + [int(piv[c].sum()) for c in piv.columns] + [
        len(s), int(s.n_cells.sum()), int(s.cores.sum()), s.zenodo_gb.sum(), s.aws_gb.sum()]
    t = t.rename(columns={"Cores": "Measurements (core x acq)"})
    L += ["## v1 by organ and modality (Zenodo = AWS membership)", "",
          "Columns per modality count acquisitions (objects).", "", md_table(t), ""]

    # --- by record
    rec = s.groupby("record").agg(Objects=("sample_id", "size"), Cells=("n_cells", "sum"),
                                  Zenodo_GB=("zenodo_gb", "sum"), AWS_GB=("aws_gb", "sum")).reset_index()
    L += ["## v1 by record / prefix", "", md_table(rec), ""]

    # --- Table 1
    t1 = None
    if TABLE1.exists():
        t1 = pd.read_excel(TABLE1).dropna(subset=["SampleID"])
    in_t1 = cov[cov.table1_id != "not in Table 1"]
    comp = in_t1.groupby("organ").agg(Table1_cores=("donor_core", lambda x: len(x)),
                                     In_release=("in_release", "sum")).reset_index()
    comp["Absent"] = comp.Table1_cores - comp.In_release
    extra = cov[cov.table1_id == "not in Table 1"].groupby("organ").size()
    comp["Not_in_Table1"] = comp.organ.map(extra).fillna(0).astype(int)
    comp["Released_cores"] = comp.In_release + comp.Not_in_Table1
    comp.loc[len(comp)] = ["**total**", int(comp.Table1_cores.sum()), int(comp.In_release.sum()),
                           int(comp.Absent.sum()), int(comp.Not_in_Table1.sum()),
                           int(comp.Released_cores.sum())]
    absent = cov[~cov.in_release][["table1_id", "organ", "why_absent"]]
    L += ["## Against Table 1", ""]
    if t1 is not None:
        n_dulai = int(t1.SampleID.astype(str).str.startswith("IBD_PD").sum())
        L += [f"Table 1 has **{len(t1)} rows**, which are not all the same kind of thing: "
              f"{len(t1) - n_dulai} are donor cores (one of them, `CRC`, pools three slides) and "
              f"{n_dulai} are Northwestern/Dulai IBD rows, one per acquisition of 20 tissue blocks. "
              "Reconciled per donor core (`zenodo/cohort_coverage.csv`): the core rows are "
              f"{len(t1) - n_dulai - 1 + 3} cores once CRC is split into its three slides, plus the "
              "20 Dulai blocks.", ""]
    L += [md_table(comp), "",
          "Absent from the release, with reason:", "", md_table(absent), "",
          "Not in Table 1 but released: `PCa_9224` (PRCA prostate cancer, 3 acquisitions), "
          "shipped with null demographics.", ""]

    # --- v2
    v2t = v2[["sample_id", "platform", "assay_type", "panel_name", "slide_id", "n_cells"]].copy()
    L += ["## AWS v2 queue", "",
          "Six acquisitions on two prostate TMA slides, delivered as four objects: each slide's "
          "CosMx RNA + protein are merged into one object (two tables, both boundary sets, "
          "registered same-section H&E); each slide's Xenium is its own object with registered "
          "serial-section H&E. All carry obs['leiden']; A2 carries donor_core for 31 cores.", "",
          md_table(v2t), "",
          md_table(pd.DataFrame({"object": v2_sizes.index, "GB": (v2_sizes / GB).round(1).values})), ""]

    # --- trees
    zrec = s.groupby("record").agg(n=("sample_id", "size"), gb=("zenodo_gb", "sum"))
    arec = s.groupby("record").agg(n=("sample_id", "size"), gb=("aws_gb", "sum"))
    tree_z = ["zenodo (13 records)",
              "├── saha-v1  (parent collection)",
              "│   ├── samples.parquet  donors.parquet  runs.parquet  panels.parquet",
              "│   ├── measurements.csv  cohort_coverage.csv  file_manifest.csv  file_manifest_cosmx.csv",
              "│   └── DESCRIPTION.md  LICENSE-DATA"]
    for i, (r, x) in enumerate(zrec.iterrows()):
        last = i == len(zrec) - 1
        tree_z.append(f"{'└' if last else '├'}── {r:<26} {int(x.n):>3} × <sample_id>.zarr.zip   {x.gb:6.1f} GB"
                      f"   + file_manifest.csv  MD5SUMS.txt  README.md")
    tree_a = ["s3://saha-open-data/",
              "├── metadata/                                  public",
              "│   ├── samples/organ=<o>/platform=<p>/*.parquet   (Hive-partitioned, Glue/Athena)",
              "│   ├── donors/  runs/  panels/",
              "│   └── measurements.csv  cohort_coverage.csv",
              "├── processed/                                public, full resolution"]
    for i, (r, x) in enumerate(arec.iterrows()):
        last = i == len(arec) - 1
        tree_a.append(f"│   {'└' if last else '├'}── {r + '/':<27} {int(x.n):>3} × <sample_id>.zarr/   {x.gb:6.1f} GB")
    by_plat = raw_in.assign(p=raw_in.s3_prefix.str.split("/").str[1]).groupby("p").bytes.sum() / 1e12
    held = raw[~raw.include].groupby("source_tree").bytes.sum() / 1e12
    tree_a += [f"├── raw/<platform>/<institution>/<run_id>/<sample_id>/   credentials only, "
               f"{raw_in.bytes.sum() / 1e12:.2f} TB for {raw_in.sample_id.nunique()} acquisitions "
               f"({', '.join(f'{k} {v:.2f} TB' for k, v in by_plat.items())})",
               f"│       not yet: TAP raw {held.get('data_TAP', 0):.2f} TB (organ-organised dirs, "
               f"not yet mapped to sample ids); Dulai has no raw (RDS only)",
               "└── docs/   README.md  DATA_DICTIONARY.md  QUICK_START.md  ACCESS_TIERS.md  FILE_FORMATS.md"]
    tree_v2 = ["s3://saha-open-data/   (after publication; private until then)",
               "├── metadata/v2/   samples  runs  donors  panels   (data/v2/*.parquet)",
               "├── processed/saha-v2-prostate/"]
    for i, (o, b) in enumerate(v2_sizes.items()):
        tree_v2.append(f"│   {'└' if i == len(v2_sizes) - 1 else '├'}── {o}.zarr/   {b / GB:5.1f} GB")
    raw2_path = REPO / "aws/raw_manifest_v2.csv"
    if raw2_path.exists():
        raw2 = pd.read_csv(raw2_path)
        tree_v2.append(f"└── raw/   credentials only, {raw2.bytes.sum() / GB:.1f} GB "
                       f"({fmt(raw2.n_files.sum())} files, aws/raw_manifest_v2.csv)")
        runs = raw2.s3_prefix.str.split("/").str[1:4].str.join("/")
        for j, (run, g) in enumerate(raw2.groupby(runs, sort=True)):
            last_run = j == runs.nunique() - 1
            tree_v2.append(f"    {'└' if last_run else '├'}── {run}/")
            pad = "    " if last_run else "│   "
            per = g.groupby("sample_id", sort=True).agg(gb=("bytes", "sum"), comps=("component", "unique"))
            for k, (sid, x) in enumerate(per.iterrows()):
                tag = "shared by both slides" if sid == "_run" else ", ".join(x.comps)
                tree_v2.append(f"    {pad}{'└' if k == len(per) - 1 else '├'}── {sid + '/':<24} "
                               f"{x.gb / GB:6.1f} GB   {tag}")
    else:
        tree_v2[-1] = tree_v2[-1].replace("├── processed", "└── processed")
    L += ["## Directory structure", "", "### Zenodo v1", "", "```", *tree_z, "```", "",
          "### AWS v1", "", "```", *tree_a, "```", "",
          "`processed/<prefix>` is the Zenodo record slug (`record_slug()`), so a record and "
          "its prefix hold the same objects.", "",
          "### AWS v2 queue (proposed: v1 convention, `saha-v2-<organ>` slug)", "",
          "```", *tree_v2, "```", ""]

    out = REPO / "docs/RELEASE_BREAKDOWN.md"
    out.write_text("\n".join(L))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
